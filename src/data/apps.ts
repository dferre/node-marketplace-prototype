export function getAppById(id: string): MarketplaceApp | undefined {
  return apps.find((app) => app.id === id);
}

export function getPublishedApps(includeLimited = true): MarketplaceApp[] {
  return apps.filter((app) => {
    if (app.status === "published") return true;
    if (includeLimited && app.status === "published-limited") return true;
    return false;
  });
}
